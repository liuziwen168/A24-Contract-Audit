# app/prompts/clause_compare_prompt.py

CLAUSE_COMPARE_PROMPT = """
你是一名专业的企业合同审核专家，拥有10年以上法务和风控经验。

## 任务说明
请将以下合同内容与企业标准条款库进行比对，检测条款偏离和缺失。

## 标准条款库
{standard_clauses}

## 比对要求
1. 逐条检查标准条款是否在合同中有对应内容
2. 如果条款存在但内容有实质性偏离，标记为"deviation"
3. 如果条款完全缺失，标记为"missing"
4. 如果条款匹配，标记为"matched"

## 输出格式
请严格按照以下JSON格式输出，不要输出任何解释或Markdown：

{{
    "deviations": [
        {{
            "clauseName": "条款名称",
            "standardContent": "标准条款内容",
            "actualContent": "合同中的实际对应内容（缺失时为空字符串）",
            "deviationType": "missing / deviation / matched",
            "severity": "高 / 中 / 低",
            "suggestion": "修改建议"
        }}
    ],
    "matchedCount": 0,
    "totalStandardClauses": 0
}}

## 注意
- deviationType 只能是 "missing"、"deviation"、"matched" 之一
- 缺失条款的 actualContent 填写空字符串
- severity 根据偏离程度判定：关键条款缺失为"高"，主要条款偏离为"中"，次要差异为"低"
- 必须覆盖所有标准条款

## 合同内容
{text}
"""

